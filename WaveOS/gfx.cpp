void drawIcon(int x, int y, int idx, int sc, uint16_t c) {
  if (idx < 0 || idx >= IC_COUNT) return;
  uint16_t hi = lerpc(c, T.white, 0.35f), lo = lerpc(c, T.bg0, 0.3f);
  for (int j = 0; j < 16; j++)
    for (int i = 0; i < 16; i++)
      if (ICONS[idx][j][i] == '#') cv.fillRect(x + i * sc + sc, y + j * sc + sc, sc, sc, T.bg0);
  for (int j = 0; j < 16; j++) {
    uint16_t col = j < 6 ? hi : (j < 11 ? c : lo);
    for (int i = 0; i < 16; i++)
      if (ICONS[idx][j][i] == '#') cv.fillRect(x + i * sc, y + j * sc, sc, sc, col);
  }
}
